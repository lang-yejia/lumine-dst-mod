local F = require("fixtures")

local function Submit(owner, pet, prefab, fields, count)
    local item = owner:Hold(F.item(prefab, fields, count))
    local action = F.action()
    return action({doer = owner, target = pet, invobject = item}), item
end

return function(test)
    test("A: action -> recording -> insight -> exact item return", function()
        F.world()
        local owner, journey, pet, bag = F.player()
        journey:Complete("lunar")
        local fields = {finiteuses = {uses = 6}, custom = {note = "keep"}, perishable = {time = 42}}
        local item = owner:Hold(F.item("moonrocknugget", fields, 3))
        item.skinname = "test_skin"
        local action, candidates, record = F.action()
        pet._owner = {value = function() return owner end}
        function item:HasTag() return false end
        local actions = {}
        candidates(item, owner, pet, actions, false)
        assert(actions[1] == record)
        assert(action({doer = owner, target = pet, invobject = item}))
        assert(item.count == 2 and not item.removed and journey.insight == 0 and pet.animation == "lookaround")
        F.tick(journey, 19)
        assert(journey.records.active and not journey.done.lunar)
        F.tick(journey, 1)
        local returned = bag.slots[1]
        assert(journey.done.lunar and journey.insight == 3 and not journey.records.active and pet.animation == "cheer")
        assert(returned.count == 1 and returned.fields.finiteuses.uses == 6 and returned.fields.custom.note == "keep")
        assert(returned.fields.perishable.time == 42 and returned.skinname == "test_skin")
        assert(#journey.records.pending == 0)
    end)
    test("B/C: reject wrong evidence, duplicates, and submissions while busy", function()
        F.world()
        local owner, journey, pet, _, inventory = F.player()
        journey:Complete("lunar")
        local ok, wrong = Submit(owner, pet, "twigs")
        assert(not ok and inventory.active == wrong and wrong:IsValid() and inventory.removals == 0)
        assert(Submit(owner, pet, "moonrocknugget"))
        local accepted, duplicate = Submit(owner, pet, "moonrocknugget")
        assert(not accepted and duplicate:IsValid() and inventory.removals == 1)
        F.tick(journey)
        local action = F.action()
        assert(not action({doer = owner, target = pet, invobject = duplicate}))
        assert(inventory.active == duplicate and journey.insight == 3 and inventory.removals == 1)
    end)
    test("D/E: full bag, capped queue, then FIFO delivery", function()
        F.world()
        local owner, journey, pet, bag, inventory = F.player()
        bag:Fill()
        for _, id in ipairs({"lunar", "deerclops", "beequeen"}) do journey:Complete(id) end
        assert(Submit(owner, pet, "moonrocknugget"))
        F.tick(journey)
        assert(Submit(owner, pet, "deerclops_eyeball"))
        F.tick(journey)
        local ok, rejected = Submit(owner, pet, "royal_jelly")
        assert(not ok and inventory.active == rejected and inventory.removals == 2 and #journey.records.pending == 2)
        bag.slots[3] = nil
        F.tick(journey, 1)
        assert(bag.slots[3].prefab == "moonrocknugget" and #journey.records.pending == 1)
        bag.slots[4] = nil
        F.tick(journey, 1)
        assert(bag.slots[4].prefab == "deerclops_eyeball" and #journey.records.pending == 0 and journey.insight == 6)
    end)
    test("F: active recording survives a save and waits for Paimon", function()
        F.world()
        local owner, journey, pet = F.player()
        journey:Complete("lunar")
        assert(Submit(owner, pet, "moonrocknugget"))
        F.tick(journey, 8)
        local new_owner, loaded, new_pet, bag = F.player(journey:OnSave())
        new_owner._paimon = nil
        F.tick(loaded, 20)
        assert(loaded.records.active.remaining == 12 and loaded.insight == 0)
        new_owner._paimon = new_pet
        F.tick(loaded, 12)
        assert(loaded.insight == 3 and bag.slots[1].prefab == "moonrocknugget")
    end)
    test("G: completed reward survives save while return is pending", function()
        F.world()
        local owner, journey, pet, bag = F.player()
        bag:Fill()
        journey:Complete("beequeen")
        assert(Submit(owner, pet, "royal_jelly", {perishable = {time = 31}}))
        F.tick(journey)
        local _, loaded, new_pet, new_bag = F.player(journey:OnSave())
        new_bag:Fill()
        F.tick(loaded, 1)
        assert(loaded.done.beequeen and loaded.insight == 1 and #loaded.records.pending == 1)
        new_bag.slots[1] = nil
        F.tick(loaded, 1)
        new_pet.satiety = 1
        assert(not require("paimon/food").TryEat(new_pet))
        assert(loaded.insight == 1 and new_bag.slots[1].fields.perishable.time == 31 and #loaded.records.pending == 0)
    end)
    test("H: consecutive records and save during container itemget", function()
        F.world()
        local owner, journey, pet, bag = F.player()
        journey:Complete("lunar")
        journey:Complete("deerclops")
        local save_during_give
        bag.on_give = function() save_during_give = F.copy(journey:OnSave()) end
        assert(Submit(owner, pet, "moonrocknugget"))
        F.tick(journey)
        assert(Submit(owner, pet, "deerclops_eyeball"))
        F.tick(journey)
        local _, loaded = F.player(save_during_give)
        assert(loaded.done.lunar and loaded.done.deerclops and loaded.insight == 6 and #loaded.records.pending == 0)
        assert(bag.slots[1].prefab == "moonrocknugget" and bag.slots[2].prefab == "deerclops_eyeball")
    end)
    test("container rejection and an exception after insertion cannot duplicate", function()
        local env = F.world()
        local owner, journey, pet, bag = F.player()
        journey:Complete("lunar")
        bag.reject = true
        env.on_spawn = function(saved) saved.data.custom = nil end
        assert(Submit(owner, pet, "moonrocknugget", {custom = {note = "keep"}}))
        F.tick(journey)
        assert(journey.insight == 3 and #journey.records.pending == 1 and not bag.slots[1])
        assert(journey.records.pending[1].item.data.custom.note == "keep")
        env.on_spawn = nil
        bag.reject = false
        bag.on_give = function() error("simulated container itemget error") end
        F.tick(journey, 2)
        assert(journey.insight == 3 and #journey.records.pending == 0 and bag.slots[1] and not bag.slots[2])
        assert(bag.slots[1].fields.custom.note == "keep")
    end)
    test("save during inventory removal retains the detached evidence", function()
        F.world()
        local owner, journey, pet, _, inventory = F.player()
        journey:Complete("lunar")
        local saved
        inventory.on_remove = function() saved = F.copy(journey:OnSave()) end
        local ok, stack = Submit(owner, pet, "moonrocknugget", nil, 2)
        assert(ok and stack.count == 1)
        local _, loaded, _, bag = F.player(saved)
        F.tick(loaded)
        assert(loaded.insight == 3 and bag.slots[1].count == 1 and not bag.slots[2])
    end)
    test("notification failure cannot block the evidence queue", function()
        F.world()
        local owner, journey, pet, bag = F.player()
        journey:Complete("lunar")
        assert(Submit(owner, pet, "moonrocknugget"))
        pet.PlayPaimonAnimation = function() error("simulated animation failure") end
        F.tick(journey, 21)
        assert(journey.insight == 3 and bag.slots[1] and not bag.slots[2] and not journey.records.busy)
    end)
    test("moon portal releases active and pending evidence once", function()
        local env = F.world()
        local owner, journey, pet, bag = F.player()
        bag:Fill()
        journey:Complete("lunar")
        journey:Complete("deerclops")
        assert(Submit(owner, pet, "moonrocknugget"))
        F.tick(journey)
        assert(Submit(owner, pet, "deerclops_eyeball"))
        local before = env.spawns
        owner:PushEvent("ms_playerreroll")
        owner:PushEvent("ms_playerreroll")
        assert(env.spawns == before + 2 and env.spawned[before + 1].position[1] == 12)
        assert(journey.insight == 3 and #journey.records.pending == 0 and not journey.records.active)
    end)
end
