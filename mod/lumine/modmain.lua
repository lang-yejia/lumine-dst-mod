    if component == nil then return end
    local ok, reason
    if active == "wind" then
        if slot == 1 then ok, reason = component:CastDash(aim_x, aim_z)
        else ok, reason = component:CastTornado(aim_x, aim_z) end
    elseif active == "electro" then
        if slot == 1 then ok, reason = component:ToggleInfusion()
        else ok, reason = component:CastBurst() end
    elseif active == "dendro" then
        if slot == 1 then ok, reason = component:CastRoot(aim_x, aim_z)
        else ok, reason = component:CastField() end
    elseif active == "hydro" then
        ok, reason = component:Cast(slot == 1 and "stream" or "bubble", aim_x, aim_z)
    elseif active == "pyro" then
        if slot == 1 then ok, reason = component:Press(nil, aim_x, aim_z)
        else ok, reason = component:ToggleBurst() end
    elseif active == "cryo" then
        ok, reason = component:Cast(slot == 1 and "infusion" or "meteor", aim_x, aim_z)
    elseif slot == 1 then ok, reason = component:CastShield()
    else ok, reason = component:CastField() end
    ElementFeedback(owner, component, ok, reason)
end)

