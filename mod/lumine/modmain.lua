local function CycleAimMode(element, slot)
    local options = aim_options[element]
    local aim = options and options[slot]
    if not aim then return end
    aim.mode = aim.mode == "mouse" and "facing" or "mouse"
    aim.changed = true
    GLOBAL.TheSim:SetPersistentString(aim.key, aim.mode, false)
end

local function CycleSkillKey(slot)
    local index = 1
    for i, value in ipairs(key_choices) do
        if value == skill_keys[slot] then index = i break end
    end
    local function UsedByOther(choice)
        for other = 1, 3 do
            if other ~= slot and skill_keys[other] == choice then return true end
        end
        return false
    end
    repeat
        index = index % #key_choices + 1
    until not UsedByOther(key_choices[index])
    skill_keys[slot] = key_choices[index]
    GLOBAL.TheSim:SetPersistentString("lumine_local_skill_keys_v2",
        skill_keys[1] .. "," .. skill_keys[2] .. "," .. skill_keys[3], false)
end

