local PyroInput = require("pyro/input")
local function ElementFeedback(owner, component, ok, reason)
    if not ok and reason ~= nil and owner.components.talker ~= nil
        and (component.last_feedback == nil or GLOBAL.GetTime() - component.last_feedback > 1) then
        component.last_feedback = GLOBAL.GetTime()
        owner.components.talker:Say(reason)
    end
end

AddModRPCHandler("LUMINE_ELEMENT", "pyro_input", function(owner, operation, input, aim_x, aim_z)
    if owner == nil or not owner:HasTag("lumine") or (input ~= PyroInput.KEY and input ~= PyroInput.BUTTON) then return end
    local pyro = owner.components.luminepyro
    if not pyro then return end
    if operation == "release" then
        pyro:Release(input)
    elseif pyro:IsResonating() and operation == "renew" then
        pyro:RenewHold(input, aim_x, aim_z)
    elseif pyro:IsResonating() and operation == "press" then
        ElementFeedback(owner, pyro, pyro:Press(input, aim_x, aim_z))
    end
end)

