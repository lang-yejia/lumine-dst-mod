AddPrefabPostInit("world", function(world)
    if not world.ismastersim then return end
    world:ListenForEvent("entity_death", function(_, event)
        local victim = event ~= nil and event.inst or nil
        if victim == nil or not victim:IsValid() or victim:HasTag("player")
            or victim.components.health == nil or victim.components.combat == nil then return end
        local boss = victim:HasTag("epic")
        if not boss and (not victim:HasTag("monster") or victim.components.health.maxhealth < 50) then return end
        local x,y,z = victim.Transform:GetWorldPosition()
        for _, player in ipairs(GLOBAL.TheSim:FindEntities(x,y,z,25,{"lumine"},{"playerghost","INLIMBO"})) do
            local journey = player.components.luminejourney
            if journey ~= nil and ProgressionData.BOSS_MILESTONES[victim.prefab]
                and journey:ParticipatedInBoss(victim) then
                journey:Complete(victim.prefab)
            end
            local artifacts = player.components.lumineartifacts
            if artifacts ~= nil and HasRelicCodex(player) and not artifacts:HasAll() and artifacts:Participated(victim)
                and (boss or math.random() < ArtifactData.DROP_CHANCE) then
                artifacts:RollDrop(victim,boss)
            end
        end
    end)
