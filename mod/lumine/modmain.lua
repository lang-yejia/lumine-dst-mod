-- DST keeps one collector per action type, component, and mod.
local inventory_collectors = {}
local function AddInventoryComponentAction(kind, component, collect)
    if component ~= "inventoryitem" or (kind ~= "INVENTORY" and kind ~= "USEITEM") then
        return AddComponentAction(kind, component, collect)
    end
    local handlers = inventory_collectors[kind]
    if handlers == nil then
        handlers = {}
        inventory_collectors[kind] = handlers
        AddComponentAction(kind, component, function(...)
            for _, handler in ipairs(handlers) do handler(...) end
        end)
    end
    handlers[#handlers + 1] = collect
end

