-- 每章 8 核心 + 8 分支 + 4 秘密；总池 40/40/20，五章各 20。
local M = { lines = {}, byid = {} }
local function Chapter(chapter, day, contexts, text)
    local i = 0
    for line in text:gmatch("[^\r\n]+") do
        line = line:match("^%s*(.-)%s*$")
        if #line > 0 then
            i = i + 1
            local secret = i > 16
            local entry = {
                id = "lore:" .. chapter .. ":" .. i, text = line, chapter = chapter,
                pool = i <= 8 and "core" or i <= 16 and "branch" or "secret",
                day = secret and 80 or day, distance = secret and 6000 or chapter == 1 and 1000 or 0,
                bosses = secret and 3 or 0, contexts = contexts,
            }
            M.lines[#M.lines + 1] = entry; M.byid[entry.id] = entry
        end
    end
    assert(i == 20, "Paimon lore chapter must contain 20 lines")
end
