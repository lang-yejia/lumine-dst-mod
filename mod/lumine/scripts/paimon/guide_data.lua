local M = { groups = {}, prefabs = {}, order = {} }
local function Add(id, name, prefabs, mobile, lines)
    local group = { id=id, name=name, mobile=mobile, lines={} }
    for i,text in ipairs(lines) do group.lines[i] = {id="guide:"..id..":"..i,text=text} end
    M.groups[id] = group
    M.order[#M.order+1] = id
    for _,prefab in ipairs(prefabs) do M.prefabs[prefab] = group end
end
