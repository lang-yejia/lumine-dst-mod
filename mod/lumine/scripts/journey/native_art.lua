local Scrapbook = require("screens/redux/scrapbookdata")

local M = {
    chapters = {
        night="campfire", cave="cave_entrance", lunar="moon_altar", sail="boat",
        seasons="winterhat", pigking="pigking", ancient_altar="ancient_altar", hermitcrab="hermitcrab",
        deerclops="deerclops", bearger="bearger", moose="moose", klaus="klaus",
        dragonfly="dragonfly", beequeen="beequeen", minotaur="minotaur", stalker_atrium="stalker_atrium",
        crabking="crabking", alterguardian_phase3="alterguardian_phase1",
    },
    proxies = {
        moon_device_construction1="moon_device",
        moon_device_construction2="moon_device",
    },
}

-- Generated by Klei from the same prefab data used in the native Scrapbook.
-- Its inventory items use a separate atlas lookup.
local cache = {}
function M.Get(id)
    if cache[id] then return cache[id] end
    local key = M.proxies[id] or id
    local entry = Scrapbook[key]
    local tex = entry and entry.tex or key .. ".tex"
    local atlas = GetScrapbookIconAtlas(tex) or GetInventoryItemAtlas(tex, true)
    if atlas then
        local image = {atlas=atlas, tex=tex}
        cache[id] = image
        return image
    end
end

return M
