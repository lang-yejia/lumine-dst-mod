local M = {groups = {}, by_id = {}}
local group

local function Group(id, title)
    group = {id = id, title = title, entries = {}}
    M.groups[#M.groups + 1] = group
end

local function Boss(id, title, kind, where, trigger, prep, fight, loot, next_step, options)
    local entry = options or {}
    entry.id, entry.title, entry.kind = id, title, kind
    entry.group, entry.where, entry.trigger = group.title, where, trigger
    entry.prep, entry.fight, entry.loot, entry.next_step = prep, fight, loot, next_step
    entry.image = entry.image or id
    M.by_id[id] = entry
    group.entries[#group.entries + 1] = entry
end

